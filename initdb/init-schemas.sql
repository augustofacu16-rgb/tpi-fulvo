-- Esquema lógico para el microservicio de Torneos (administrado por servicio-torneos)
CREATE SCHEMA IF NOT EXISTS esquema_torneos;

-- Esquema lógico para el microservicio de Operaciones y Partidos (administrado por servicio-operaciones-partidos)
CREATE SCHEMA IF NOT EXISTS esquema_operaciones;

CREATE TABLE IF NOT EXISTS esquema_operaciones.partido
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_id           BIGINT       NOT NULL,
    formato_torneo      VARCHAR(255) NOT NULL,
    fecha_o_fase        INTEGER      NOT NULL,
    equipo_local_id     BIGINT,
    equipo_visitante_id BIGINT,
    fecha_hora          TIMESTAMP WITHOUT TIME ZONE,
    estado              VARCHAR(255) NOT NULL
    CHECK (estado IN (
           'PROGRAMADO',
           'EN_CURSO',
           'FINALIZADO',
           'REPROGRAMADO',
           'SUSPENDIDO',
           'CANCELADO'
                     ))
    );

CREATE TABLE IF NOT EXISTS esquema_operaciones.sede
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(255) NOT NULL,
    direccion VARCHAR(255) NOT NULL,
    latitud   DOUBLE PRECISION,
    longitud  DOUBLE PRECISION
    );

CREATE TABLE IF NOT EXISTS esquema_operaciones.arbitro
(
    dni              VARCHAR(255) PRIMARY KEY,
    usuario_id       VARCHAR(255) NOT NULL,
    nombre           VARCHAR(255) NOT NULL,
    apellido         VARCHAR(255) NOT NULL,
    asignado_partido BOOLEAN      NOT NULL DEFAULT FALSE
    );

ALTER TABLE esquema_operaciones.partido
    ADD COLUMN IF NOT EXISTS sede_id           BIGINT
    REFERENCES esquema_operaciones.sede (id),
    ADD COLUMN IF NOT EXISTS arbitro_dni       VARCHAR(255)
    REFERENCES esquema_operaciones.arbitro (dni),
    ADD COLUMN IF NOT EXISTS goles_local       INTEGER,
    ADD COLUMN IF NOT EXISTS goles_visitante   INTEGER,
    ADD COLUMN IF NOT EXISTS penales_local     INTEGER,
    ADD COLUMN IF NOT EXISTS penales_visitante INTEGER,
    ADD COLUMN IF NOT EXISTS ganador_equipo_id BIGINT;

CREATE TABLE IF NOT EXISTS esquema_operaciones.actuacion_jugador
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partido_id     BIGINT       NOT NULL
    REFERENCES esquema_operaciones.partido (id),
    equipo_id      BIGINT       NOT NULL,
    dorsal_jugador INTEGER      NOT NULL,
    tipo           VARCHAR(255) NOT NULL
    CHECK (tipo IN (
           'GOL',
           'TARJETA_AMARILLA',
           'TARJETA_ROJA'
                   ))
    );

CREATE TABLE IF NOT EXISTS esquema_operaciones.tabla_posicion
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_id          BIGINT  NOT NULL,
    equipo_id          BIGINT  NOT NULL,
    partidos_jugados   INTEGER NOT NULL DEFAULT 0,
    partidos_ganados   INTEGER NOT NULL DEFAULT 0,
    partidos_empatados INTEGER NOT NULL DEFAULT 0,
    partidos_perdidos  INTEGER NOT NULL DEFAULT 0,
    goles_a_favor      INTEGER NOT NULL DEFAULT 0,
    goles_en_contra    INTEGER NOT NULL DEFAULT 0,
    diferencia_gol     INTEGER NOT NULL DEFAULT 0,
    puntos             INTEGER NOT NULL DEFAULT 0
);