-- Carga aditiva de un torneo LLAVES de prueba (8 equipos, 15 jugadores por equipo).
-- Requiere haber aplicado init-schemas.sql. No ejecutar el seed general después:
-- sus DELETE por torneo_id podrían eliminar otros datos.
-- Ejecutar con psql -v ON_ERROR_STOP=1. No usar --single-transaction: ya tiene BEGIN.
-- Los nextval pueden dejar huecos si hay rollback; nunca se retroceden secuencias.
\set ON_ERROR_STOP on
\if :{?seed_nombre}
\else
\set seed_nombre 'TEST LLAVES 8 - carga aislada v1'
\endif
BEGIN;
SET LOCAL lock_timeout = '10s';

-- Asegurar esquemas
CREATE SCHEMA IF NOT EXISTS esquema_torneos;
CREATE SCHEMA IF NOT EXISTS esquema_operaciones;

-- Asegurar tablas de esquema_torneos
CREATE TABLE IF NOT EXISTS esquema_torneos.torneo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    formato VARCHAR(20) NOT NULL,
    cupo_equipos INTEGER NOT NULL,
    estado VARCHAR(30) NOT NULL,
    fecha_inicio TIMESTAMP WITHOUT TIME ZONE,
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS esquema_torneos.solicitud_inscripcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_id BIGINT NOT NULL REFERENCES esquema_torneos.torneo(id),
    fanatico_usuario_id VARCHAR(100) NOT NULL,
    nombre_equipo VARCHAR(100) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    fecha_solicitud TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    motivo_rechazo VARCHAR(255),
    datos_plantel_json TEXT
);

CREATE TABLE IF NOT EXISTS esquema_torneos.equipo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_id BIGINT NOT NULL REFERENCES esquema_torneos.torneo(id),
    solicitud_id BIGINT NOT NULL UNIQUE REFERENCES esquema_torneos.solicitud_inscripcion(id),
    nombre VARCHAR(100) NOT NULL,
    delegado_usuario_id VARCHAR(100) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    cambios_realizados INTEGER NOT NULL DEFAULT 0,
    fecha_alta TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS esquema_torneos.jugador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR(20) NOT NULL,
    equipo_id BIGINT NOT NULL REFERENCES esquema_torneos.equipo(id),
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    dorsal INTEGER NOT NULL,
    posicion VARCHAR(30) NOT NULL,
    es_capitan BOOLEAN NOT NULL DEFAULT false,
    activo BOOLEAN NOT NULL DEFAULT true,
    suspendido BOOLEAN NOT NULL DEFAULT false
);

-- Serializar la carga con escrituras sobre las tablas consultadas.
LOCK TABLE esquema_torneos.torneo, esquema_torneos.solicitud_inscripcion,
    esquema_torneos.equipo, esquema_torneos.jugador,
    esquema_operaciones.partido, esquema_operaciones.actuacion_jugador,
    esquema_operaciones.tabla_posicion IN SHARE ROW EXCLUSIVE MODE;

CREATE TEMP TABLE seed_llaves_resultado (torneo_id BIGINT) ON COMMIT DROP;
CREATE TEMP TABLE seed_llaves_opciones (nombre TEXT NOT NULL) ON COMMIT DROP;
INSERT INTO seed_llaves_opciones VALUES (:'seed_nombre');

-- Consumir la secuencia de identidad hasta encontrar una PK disponible.
-- Esto también tolera secuencias atrasadas por inserciones manuales previas.
CREATE FUNCTION pg_temp.seed_id_libre(tabla REGCLASS)
RETURNS BIGINT LANGUAGE plpgsql AS $func$
DECLARE
    candidato BIGINT;
    ocupado BOOLEAN;
    secuencia TEXT;
BEGIN
    secuencia := pg_get_serial_sequence(tabla::TEXT, 'id');
    IF secuencia IS NULL THEN
        RAISE EXCEPTION 'La tabla % no tiene secuencia de identidad', tabla;
    END IF;
    LOOP
        candidato := nextval(secuencia::REGCLASS);
        EXECUTE format('SELECT EXISTS (SELECT 1 FROM %s WHERE id = $1)', tabla)
            INTO ocupado USING candidato;
        IF NOT ocupado THEN
            RETURN candidato;
        END IF;
    END LOOP;
END;
$func$;

DO $seed$
DECLARE
    nombre_seed TEXT;
    torneo_nuevo BIGINT;
    equipo_nuevo BIGINT;
    solicitud_nueva BIGINT;
    jugador_nuevo BIGINT;
    equipos BIGINT[] := ARRAY[]::BIGINT[];
    nombres TEXT[] := ARRAY['Real Madrid', 'Barcelona', 'Liverpool', 'Manchester City',
                            'Bayern Munich', 'Paris Saint-Germain', 'Inter', 'Juventus'];
    i INTEGER;
    dorsal INTEGER;
    dni_candidato BIGINT := 80000000;
    posicion TEXT;
BEGIN
    SELECT nombre INTO STRICT nombre_seed FROM seed_llaves_opciones;
    -- Reejecutar no reinicia resultados ni duplica el torneo.
    SELECT id INTO torneo_nuevo FROM esquema_torneos.torneo
    WHERE nombre = nombre_seed ORDER BY id LIMIT 1;
    IF FOUND THEN
        INSERT INTO seed_llaves_resultado VALUES (torneo_nuevo);
        RAISE NOTICE 'El torneo de prueba ya existe (ID %); se conservan sus datos', torneo_nuevo;
        RETURN;
    END IF;

    -- Evitar que el nuevo torneo adopte partidos o estadísticas huérfanas.
    LOOP
        torneo_nuevo := pg_temp.seed_id_libre('esquema_torneos.torneo');
        EXIT WHEN NOT EXISTS (
            SELECT 1 FROM esquema_operaciones.partido WHERE torneo_id = torneo_nuevo
            UNION ALL
            SELECT 1 FROM esquema_operaciones.tabla_posicion WHERE torneo_id = torneo_nuevo
        );
    END LOOP;

    INSERT INTO esquema_torneos.torneo
        (id, nombre, formato, cupo_equipos, estado, fecha_inicio, fecha_creacion)
    VALUES (torneo_nuevo, nombre_seed, 'LLAVES', 8, 'INICIADO', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);

    FOR i IN 1..8 LOOP
        LOOP
            equipo_nuevo := pg_temp.seed_id_libre('esquema_torneos.equipo');
            EXIT WHEN NOT EXISTS (
                SELECT 1 FROM esquema_operaciones.partido
                WHERE equipo_local_id = equipo_nuevo OR equipo_visitante_id = equipo_nuevo
                   OR ganador_equipo_id = equipo_nuevo
                UNION ALL
                SELECT 1 FROM esquema_operaciones.actuacion_jugador WHERE equipo_id = equipo_nuevo
                UNION ALL
                SELECT 1 FROM esquema_operaciones.tabla_posicion WHERE equipo_id = equipo_nuevo
            );
        END LOOP;

        solicitud_nueva := pg_temp.seed_id_libre('esquema_torneos.solicitud_inscripcion');
        INSERT INTO esquema_torneos.solicitud_inscripcion
            (id, torneo_id, fanatico_usuario_id, nombre_equipo, estado, fecha_solicitud, datos_plantel_json)
        VALUES (solicitud_nueva, torneo_nuevo, 'seed-llaves-delegado-' || equipo_nuevo,
                nombres[i], 'ACEPTADA', CURRENT_TIMESTAMP, '[]');

        INSERT INTO esquema_torneos.equipo
            (id, torneo_id, solicitud_id, nombre, delegado_usuario_id, estado, cambios_realizados, fecha_alta)
        VALUES (equipo_nuevo, torneo_nuevo, solicitud_nueva, nombres[i],
                'seed-llaves-delegado-' || equipo_nuevo, 'ACTIVO', 0, CURRENT_TIMESTAMP);
        equipos := array_append(equipos, equipo_nuevo);

        FOR dorsal IN 1..15 LOOP
            LOOP
                dni_candidato := dni_candidato + 1;
                IF dni_candidato > 99999999 THEN
                    RAISE EXCEPTION 'Se agotó el rango de DNI de prueba';
                END IF;
                EXIT WHEN NOT EXISTS (
                    SELECT 1 FROM esquema_torneos.jugador WHERE dni = dni_candidato::TEXT
                );
            END LOOP;
            posicion := CASE WHEN dorsal IN (1, 12) THEN 'ARQUERO'
                             WHEN dorsal BETWEEN 2 AND 5 THEN 'DEFENSOR'
                             WHEN dorsal BETWEEN 6 AND 9 THEN 'VOLANTE'
                             ELSE 'DELANTERO' END;
            jugador_nuevo := pg_temp.seed_id_libre('esquema_torneos.jugador');
            INSERT INTO esquema_torneos.jugador
                (id, dni, equipo_id, nombre, apellido, dorsal, posicion, es_capitan, activo, suspendido)
            VALUES (jugador_nuevo, dni_candidato::TEXT, equipo_nuevo, 'Jugador ' || dorsal,
                    nombres[i], dorsal, posicion, dorsal = 2, true, false);
        END LOOP;

        -- Solo completa la solicitud recién creada con el plantel de ese equipo.
        UPDATE esquema_torneos.solicitud_inscripcion
        SET datos_plantel_json = (
            SELECT jsonb_agg(jsonb_build_object(
                'dni', j.dni, 'nombre', j.nombre, 'apellido', j.apellido,
                'posicion', j.posicion, 'dorsal', j.dorsal, 'esCapitan', j.es_capitan
            ) ORDER BY j.dorsal)::TEXT
            FROM esquema_torneos.jugador j WHERE j.equipo_id = equipo_nuevo
        )
        WHERE id = solicitud_nueva;
    END LOOP;

    FOR i IN 1..4 LOOP
        INSERT INTO esquema_operaciones.partido
            (id, torneo_id, formato_torneo, fecha_o_fase, equipo_local_id, equipo_visitante_id, estado)
        VALUES (pg_temp.seed_id_libre('esquema_operaciones.partido'),
                torneo_nuevo, 'LLAVES', 1, equipos[i], equipos[9-i], 'PROGRAMADO');
    END LOOP;
    FOR i IN 1..2 LOOP
        INSERT INTO esquema_operaciones.partido
            (id, torneo_id, formato_torneo, fecha_o_fase, estado)
        VALUES (pg_temp.seed_id_libre('esquema_operaciones.partido'),
                torneo_nuevo, 'LLAVES', 2, 'PROGRAMADO');
    END LOOP;
    INSERT INTO esquema_operaciones.partido
        (id, torneo_id, formato_torneo, fecha_o_fase, estado)
    VALUES (pg_temp.seed_id_libre('esquema_operaciones.partido'),
            torneo_nuevo, 'LLAVES', 3, 'PROGRAMADO');

    INSERT INTO seed_llaves_resultado VALUES (torneo_nuevo);
END;
$seed$;

SELECT t.id, t.nombre, t.formato, t.estado,
       (SELECT count(*) FROM esquema_torneos.equipo e WHERE e.torneo_id = t.id) AS equipos,
       (SELECT count(*) FROM esquema_torneos.jugador j
        JOIN esquema_torneos.equipo e ON e.id = j.equipo_id WHERE e.torneo_id = t.id) AS jugadores,
       (SELECT count(*) FROM esquema_operaciones.partido p WHERE p.torneo_id = t.id) AS partidos
FROM esquema_torneos.torneo t JOIN seed_llaves_resultado r ON r.torneo_id = t.id;

SELECT p.id, p.torneo_id, p.fecha_o_fase, p.equipo_local_id,
       p.equipo_visitante_id, p.estado
FROM esquema_operaciones.partido p JOIN seed_llaves_resultado r ON r.torneo_id = p.torneo_id
ORDER BY p.fecha_o_fase, p.id;

COMMIT;
